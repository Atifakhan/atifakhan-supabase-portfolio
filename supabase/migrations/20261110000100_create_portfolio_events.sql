-- Public portfolio event cards. Public clients can read published rows only.
create table public.portfolio_events (
  id bigint generated by default as identity primary key,
  title text not null,
  venue text not null,
  event_date date,
  summary text not null,
  role text not null default 'Community organizer',
  source_url text,
  image_url text,
  is_published boolean not null default false,
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);

alter table public.portfolio_events enable row level security;
revoke all on public.portfolio_events from public, anon, authenticated;
grant select on public.portfolio_events to anon, authenticated;

create policy "Public can read published portfolio events"
  on public.portfolio_events
  for select
  to anon, authenticated
  using (is_published = true);

